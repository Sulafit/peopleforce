// Keeps the no-build version in prototype/ in step with the Next.js app.
// Run with `npm run sync:prototype` after changing data/roadmap.json or app/globals.css.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "prototype");

for (const dir of ["css", "js", "fonts"]) {
  mkdirSync(join(out, dir), { recursive: true });
}

// 1. Roadmap content: one JSON file feeds both builds.
const roadmap = readFileSync(join(root, "data", "roadmap.json"), "utf8");
writeFileSync(
  join(out, "js", "data.js"),
  `// Generated from data/roadmap.json by scripts/sync-prototype.mjs. Do not edit by hand.\nwindow.FGOS_ROADMAP = ${roadmap.trim()};\n`,
);

// 2. Styles: app/globals.css is the source of truth.
copyFileSync(join(root, "app", "globals.css"), join(out, "css", "styles.css"));

// 3. Fonts: self-hosted Latin subsets, so the prototype pages work offline.
const fonts = [
  { pkg: "fredoka", file: "fredoka-latin-wght-normal.woff2", family: "Fredoka Variable", weight: "300 700" },
  { pkg: "nunito", file: "nunito-latin-wght-normal.woff2", family: "Nunito Variable", weight: "200 1000" },
];

let css = "/* Generated by scripts/sync-prototype.mjs. Fonts are SIL OFL 1.1, from Fontsource. */\n";
for (const font of fonts) {
  copyFileSync(
    join(root, "node_modules", "@fontsource-variable", font.pkg, "files", font.file),
    join(out, "fonts", font.file),
  );
  css += `@font-face {\n  font-family: "${font.family}";\n  font-style: normal;\n  font-display: swap;\n  font-weight: ${font.weight};\n  src: url("../fonts/${font.file}") format("woff2-variations");\n}\n`;
}
writeFileSync(join(out, "css", "fonts.css"), css);

console.log("prototype/ synced: js/data.js, css/styles.css, css/fonts.css, fonts/");
